from argparse import ArgumentParser
import json
from pathlib import Path
import time
from typing import Any, OrderedDict, Callable

from prometheus_client import CollectorRegistry, Counter, Gauge, push_to_gateway
from prometheus_client.registry import Collector

from screeps_prometheus.prometheus import PrometheusConfig
from screeps_prometheus.screeps import ScreepsConfig, TokenAuth


type ScreepsStats = dict[str, Any]
type StatScraper = Callable[[], ScreepsStats | None]

parser = ArgumentParser(description='Daemon for Scraping Screeps Stats into Prometheus.')
parser.add_argument("--screeps-token", "-token", type=str, help='Simple way of connecting to main MMO.')
parser.add_argument("--screeps-config", "-sc", type=Path, default="screeps.json", help='Use to connect to worlds other than MMO.')

parser.add_argument("--prometheus-config", "-pc", type=Path, default="prometheus.json")


def get_instrument_for_stat(name: str, val: Any, registry: CollectorRegistry) -> Collector:
    if name == "time":
        return Gauge("time", "The current in gametime as of which the stats are valid.", registry=registry)

    if isinstance(val, int | float):
        return Gauge(name, f"Autogenerated Gauge for {name}", registry=registry)

    raise Exception(f"Can't find a Collector for {name!r} with value {val!r}")


def scrape_stats(collectors: dict[str, Collector], registry: CollectorRegistry, statGetter: StatScraper) -> None:
    currentStats: ScreepsStats | None = statGetter()

    if currentStats is None or len(currentStats) == 1:
        print(f"No stats exist")
        return
    elif not (currentStats and currentStats["ok"]):
        raise Exception(f'Fetching Memory was not OK: {currentStats["ok"]}')

    count = 0
    for statK, statV in currentStats["data"].items():
        collector = collectors.get(statK)

        if collector is None:
            raise Exception(f"Expected a collector to exist already for {statK}")

        collector.set(statV) # type: ignore
        count+=1

    print(f"Scraped {count} stats successfully.")

def main() -> None:
    args = parser.parse_args()

    if args.screeps_token is not None:
        screepsConfig = ScreepsConfig(TokenAuth(token=args.screeps_token))
    elif args.screeps_config is not None:
        screepsConfig = ScreepsConfig.from_file(args.screeps_config)
    else:
        raise Exception('Missing `--screeps-token` and `--screeps-config`!')

    prometheusConfig = PrometheusConfig.from_file(args.prometheus_config)

    screepsApi = screepsConfig.login()
    statGetter: StatScraper = lambda: screepsApi.memory(path="stats", shard=screepsConfig.shard)

    me: OrderedDict = screepsApi.me() # type: ignore

    print(f"Logged into Screeps as {me["email"]}")

    initialStats: ScreepsStats | None = statGetter()
    if initialStats is None or len(initialStats) == 1:
        print(f"No stats exist")
        return
    elif initialStats and initialStats["ok"]:
        print(f"Initial stat fetch was successful: {json.dumps(initialStats, indent=2)}")
    else:
        raise Exception(f'Fetching Memory was not OK: {initialStats["ok"]}')

    registry = CollectorRegistry()
    instruments = { name: get_instrument_for_stat(name, val, registry) for name, val in initialStats["data"].items() }
    scrape_stats(instruments, registry, statGetter)

    while True:
        time.sleep(5)
        scrape_stats(instruments, registry, statGetter)
        push_to_gateway(gateway=prometheusConfig.gateway, job=prometheusConfig.jobName, registry=registry)
